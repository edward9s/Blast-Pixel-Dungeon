#!/usr/bin/env bash
set -euo pipefail

upstream="${1:?usage: apply.sh <upstream-root> <blast-root>}"
blast="${2:?missing Blast root}"
root="$upstream/core/src/main/java/com/shatteredpixel/shatteredpixeldungeon"
patches="$blast/integration/shattered/patches"

test -f "$upstream/build.gradle"
test -d "$patches"
test -d "$root"

python "$patches/patch_app_package.py" "$upstream/build.gradle"
python "$patches/patch_android_manifest.py" "$upstream/android/src/main/AndroidManifest.xml"
python "$patches/patch_tag_keybindings.py" "$root/SPDAction.java" "$root/windows/WndKeyBindings.java"
python "$patches/patch_wndsettings.py" "$root/windows/WndSettings.java"
python "$patches/patch_title_scene.py" "$root/scenes/TitleScene.java"
python "$patches/patch_shattered_support.py" "$root/scenes/TitleScene.java" "$root/items/keys/WornKey.java"
python "$patches/patch_about_scene.py" "$root/scenes/AboutScene.java"
python "$patches/patch_assets.py" "$root/Assets.java" "$upstream/core/src/main/assets" "$blast/core/src/main/assets"
python "$patches/patch_icons.py" "$upstream" "$blast/assets/app-icons"
python "$patches/patch_menu_pane.py" "$root/ui/MenuPane.java"
python "$patches/patch_mob_spawner.py" "$root/actors/mobs/MobSpawner.java"
python "$patches/patch_mob.py" "$root/actors/mobs/Mob.java"
python "$patches/patch_catalog.py" "$root/journal/Catalog.java"
python "$patches/patch_level.py" "$root/levels/Level.java"
python "$patches/patch_regular_level.py" "$root/levels/RegularLevel.java"
python "$patches/patch_dungeon_terrain_tilemap.py" "$root/tiles/DungeonTerrainTilemap.java"
python "$patches/patch_hero.py" "$root/actors/hero/Hero.java"
python "$patches/patch_bomb.py" "$root/items/bombs/Bomb.java"
python "$patches/patch_shrapnel_bomb.py" "$root/items/bombs/ShrapnelBomb.java"
python "$patches/patch_bomb_visuals.py" "$root/items/bombs"
python "$patches/patch_bomb_walls.py" "$root/items/bombs/Bomb.java"
python "$patches/patch_wnd_info_cell.py" "$root/windows/WndInfoCell.java"
for kind in Firebomb FrostBomb HolyBomb SmokeBomb RegrowthBomb WoollyBomb ArcaneBomb FlashBangBomb; do
  python "$patches/patch_bomb_ranges.py" "$root/items/bombs/$kind.java"
done
python "$patches/patch_heap.py" "$root/items/Heap.java"
python "$patches/patch_item_sprite.py" "$root/sprites/ItemSprite.java"
python "$patches/patch_item_slot.py" "$root/ui/ItemSlot.java"
python "$patches/patch_loot_indicator.py" "$root/ui/LootIndicator.java"
python "$patches/patch_wndjournal.py" "$root/windows/WndJournal.java"
python "$patches/patch_game_scene.py" "$root/scenes/GameScene.java"
python "$patches/patch_messages.py" "$upstream/core/src/main/assets/messages/misc" "$blast/messages"
